# Put EMAIL_HOST_USER / EMAIL_HOST_PASSWORD in a file named ".env" next to manage.py
# (".env.txt" is also accepted, because Windows Notepad likes to add ".txt").
for _name in ('.env', '.env.txt'):
    _env_file = Path(__file__).resolve().parent.parent / _name
    if not _env_file.exists():
        continue
    try:
        for _line in _env_file.read_text(encoding='utf-8-sig', errors='ignore').splitlines():
            _line = _line.strip()
            if _line and not _line.startswith('#') and '=' in _line:
                _k, _v = _line.split('=', 1)
                os.environ.setdefault(_k.strip(), _v.strip().strip('"').strip("'"))
    except OSError:
        pass

